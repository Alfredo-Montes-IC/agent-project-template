"""Generate trusted branch cleanup workflow without checking out repository code."""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parents[1]
HEADER='''# Generated by scripts/sync_cleanup_workflow.py.
name: Delete merged task branches

on:
  pull_request_target:
    types: [closed]
  push:
    branches: [main]
    paths: ['.github/workflows/cleanup-branches.yml']
  workflow_dispatch:

permissions:
  contents: write
  pull-requests: read

concurrency:
  group: merged-task-branch-cleanup
  cancel-in-progress: false

jobs:
  cleanup:
    if: github.event_name != 'pull_request_target' || (github.event.pull_request.merged == true && (github.event.pull_request.base.ref == 'dev' || github.event.pull_request.base.ref == 'main'))
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - name: Delete only verified merged task heads (no checkout)
        env:
          GH_TOKEN: ${{ github.token }}
        run: |
          python3 - <<'PYTHON'
'''
def render(root=ROOT):
    body=(root/'scripts/cleanup_merged_branches.py').read_text().rstrip()
    return HEADER+'\n'.join('          '+line if line else '' for line in body.splitlines())+'\n          PYTHON\n'
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    target=ROOT/'.github/workflows/cleanup-branches.yml'; expected=render()
    if a.check:
        if not target.exists() or target.read_text()!=expected:
            print('Cleanup workflow drift; run python3 scripts/sync_cleanup_workflow.py');return 1
    else: target.write_text(expected)
    print('Trusted cleanup workflow matches source.');return 0
if __name__=='__main__':raise SystemExit(main())
