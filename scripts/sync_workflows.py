"""Generate trusted metadata-only routing workflow; no checkout of untrusted PR code."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
HEADER = '''# Generated by scripts/sync_workflows.py; do not hand-edit the embedded policy.
name: Trusted PR routing

on:
  pull_request_target:
    types: [opened, synchronize, reopened, edited, ready_for_review]

permissions:
  contents: read

jobs:
  branch-policy:
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - name: Check metadata using trusted base workflow (no checkout)
        env:
          PR_BASE: ${{ github.event.pull_request.base.ref }}
          PR_HEAD: ${{ github.event.pull_request.head.ref }}
          PR_HEAD_REPO: ${{ github.event.pull_request.head.repo.full_name }}
          PR_BASE_REPO: ${{ github.event.pull_request.base.repo.full_name }}
        run: |
          python3 - <<'PYTHON'
'''

def render(root=ROOT):
    body=(root/'scripts/pr_routing.py').read_text().rstrip()
    return HEADER + '\n'.join('          '+line if line else '' for line in body.splitlines()) + "\n          PYTHON\n"

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    target=ROOT/'.github/workflows/branch-policy.yml'
    expected=render()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            print('Trusted routing workflow drift; run python3 scripts/sync_workflows.py')
            return 1
    else:
        target.write_text(expected)
    print('Trusted routing workflow matches its policy source.')
    return 0

if __name__=='__main__':raise SystemExit(main())
